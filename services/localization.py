# Collision-free reverse resolution to canonical English
_REVERSE_TO_ENGLISH: Final[dict[str, str]] = {}

# 1. Seed identity mapping for all canonical English keys
for _canon_key in TRANSLATIONS["ru"].keys():
    _REVERSE_TO_ENGLISH[_canon_key] = _canon_key

# 2. Add localized strings mapping back to English without overwriting canonical English words
for _sub_dict in TRANSLATIONS.values():
    for _canon, _trans in _sub_dict.items():
        if _trans not in _REVERSE_TO_ENGLISH:
            _REVERSE_TO_ENGLISH[_trans] = _canon

# 3. Add historical aliases
for _alias, _canon in _HISTORICAL_ALIASES.items():
    if _alias not in _REVERSE_TO_ENGLISH:
        _REVERSE_TO_ENGLISH[_alias] = _canon


def _source_text(text: str) -> str:
    """Return the canonical English source for text in any supported locale."""
    return _REVERSE_TO_ENGLISH.get(text, text)


def translate(text: str, locale: str, **kwargs: Any) -> str:
    """Translate an interface string, falling back to English when needed."""
    if not text:
        return ""
    source = _source_text(text)
    if locale == "en":
        result = source
    else:
        result = TRANSLATIONS.get(locale, {}).get(source, source)
    if kwargs:
        try:
            return result.format(**kwargs)
        except (KeyError, ValueError, IndexError):
            return result
    return result


def translate_many(texts: list[str] | tuple[str, ...], locale: str) -> list[str]:
    """Translate a collection of UI strings while preserving its order."""
    return [translate(text, locale) for text in texts]


def locale_name(locale: str) -> str:
    """Return the display name of a locale."""
    return LOCALE_NAMES.get(locale, LOCALE_NAMES["en"])
