_REVERSE_EXACT_MAP: Final[dict[str, str]] = {
    translated: source for source, translated in ENGLISH_TRANSLATIONS.items()
}
for _sub_dict in ADDITIONAL_TRANSLATIONS.values():
    _REVERSE_EXACT_MAP.update({translated: source for source, translated in _sub_dict.items()})

_SORTED_FRAGMENT_REPLACEMENTS: Final[list[tuple[str, str]]] = sorted(
    ((target, source_fragment) for source_fragment, target in ENGLISH_FRAGMENT_TRANSLATIONS.items()),
    key=lambda item: len(item[0]),
    reverse=True,
)


def _source_text(text: str) -> str:
    """Return the stable Russian source for text in any supported locale."""
    source = _REVERSE_EXACT_MAP.get(text, text)
    for translated_fragment, source_fragment in _SORTED_FRAGMENT_REPLACEMENTS:
        if translated_fragment in source:
            source = source.replace(translated_fragment, source_fragment)
    return source


def translate(text: str, locale: str) -> str:
    """Translate an interface string, falling back to English when needed."""
    source = _source_text(text)
    if locale == "ru":
        return source

    if locale == "en":
        translated = ENGLISH_TRANSLATIONS.get(source, source)
        for source, target in ENGLISH_FRAGMENT_TRANSLATIONS.items():
            translated = translated.replace(source, target)
        return translated

    localized = ADDITIONAL_TRANSLATIONS.get(locale, {})
    if source in localized:
        return localized[source]

    translated = ENGLISH_TRANSLATIONS.get(source, source)
    for source, target in ENGLISH_FRAGMENT_TRANSLATIONS.items():
        translated = translated.replace(source, target)
    return translated


def translate_many(texts: list[str] | tuple[str, ...], locale: str) -> list[str]:
    """Translate a collection of UI strings while preserving its order."""
    return [translate(text, locale) for text in texts]


def locale_name(locale: str) -> str:
    """Return the display name of a locale."""
    return LOCALE_NAMES.get(locale, LOCALE_NAMES["ru"])
